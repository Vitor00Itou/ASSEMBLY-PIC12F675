#INCLUDE <p12f675.inc>	;ARQUIVO PADRÃO MICROCHIP PARA 12F675

	__CONFIG _BODEN_OFF & _CP_OFF & _PWRTE_ON & _WDT_OFF & _MCLRE_ON & _INTRC_OSC_NOCLKOUT

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                    PAGINAÇÃO DE MEMÓRIA                         *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;DEFINIÇÃO DE COMANDOS DE USUÁRIO PARA ALTERAÇÃO DA PÁGINA DE MEMÓRIA
#DEFINE	BANK0	BCF STATUS,RP0	;SETA BANK 0 DE MEMÓRIA
#DEFINE	BANK1	BSF STATUS,RP0	;SETA BANK 1 DE MAMÓRIA

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                         VARIÁVEIS                               *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
; DEFINIÇÃO DOS NOMES E ENDEREÇOS DE TODAS AS VARIÁVEIS UTILIZADAS 
; PELO SISTEMA

	CBLOCK	0x20	;ENDEREÇO INICIAL DA MEMÓRIA DE
					;USUÁRIO
		W_TEMP		;REGISTRADORES TEMPORÁRIOS PARA USO
		STATUS_TEMP	;JUNTO ÀS INTERRUPÇÕES

		;COLOQUE AQUI SUAS NOVAS VARIÁVEIS
		;NÃO ESQUEÇA COMENTÁRIOS ESCLARECEDORES
		
		FLAG_VERIFICADOR_CICLO  ;BIT 0:  0 = DESCENDO TENSÃO,  1 = SUBINDO TENSÃO
					;BIT 1:  0 = NENHUM TESTE FEITO NESSE CICLO DE CHECAGEM,  1 = FORAM FEITOS TESTES NESSE CICLO
					;BIT 2:  0 = FIM DE UM PERÍODO DO SINAL, 1 = PERÍODO DO SINAL SENDO EXECUTADO
					;BIT 3-7: NÃO FORAM IMPLEMENTADOS
					
		VARIAVEL_DELAY		;VARIAVEL PARA DECREMENTAR EM UM DELAY
		
		CONFIG_COMPARADOR	;GUARDA O VALOR PARA CONFIGURAR O COMPARADOR
					;0 -> 0,5V
					;1 -> 1V
					;2 -> 1,5V
					;3 -> 2V
					;4 -> 2.5V
					;5 -> 3V
					;6 -> 3,5V
				
		SELECIONA_DUTY ;GUARDA O VALOR PARA ACIONAR O CICLO ATUAL
					;0 -> 0 - 0,5V (LED DESLIGADO)
					;1 -> 0,5 - 1V (5%)
					;2 -> 1 - 1,5V (10%)
					;3 -> 1,5 - 2V (20%)
					;4 -> 2V - 2.5V (30%)
					;5 -> 2.5V - 3V	(40%)
					;6 -> 3V - 3,5V (80%)
					;7 -> MAIOR QUE 3,5 (LED LIGADO)
					
		TEMPO_LIGADO  ;VARIAVEL QUE ARMAZENA A QUANTIDADE DE TEMPOS DE 100 MICROSEGUNDOS QUE O LED VAI FICAR LIGADO
		TEMPO_DESLIGADO  ;VARIAVEL QUE ARMAZENA A QUANTIDADE DE TEMPOS DE 100 MICROSEGUNDOS QUE O LED VAI FICAR DESLIGADO
					
		
		

	ENDC			;FIM DO BLOCO DE DEFINIÇÃO DE VARIÁVEIS

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                        FLAGS INTERNOS                           *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
; DEFINIÇÃO DE TODOS OS FLAGS UTILIZADOS PELO SISTEMA

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                         CONSTANTES                              *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
; DEFINIÇÃO DE TODAS AS CONSTANTES UTILIZADAS PELO SISTEMA

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                           ENTRADAS                              *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
; DEFINIÇÃO DE TODOS OS PINOS QUE SERÃO UTILIZADOS COMO ENTRADA
; RECOMENDAMOS TAMBÉM COMENTAR O SIGNIFICADO DE SEUS ESTADOS (0 E 1)

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                           SAÍDAS                                *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
; DEFINIÇÃO DE TODOS OS PINOS QUE SERÃO UTILIZADOS COMO SAÍDA
; RECOMENDAMOS TAMBÉM COMENTAR O SIGNIFICADO DE SEUS ESTADOS (0 E 1)

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                       VETOR DE RESET                            *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *

	ORG	0x00			;ENDEREÇO INICIAL DE PROCESSAMENTO
	GOTO	INICIO
	
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                    INÍCIO DA INTERRUPÇÃO                        *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
; ENDEREÇO DE DESVIO DAS INTERRUPÇÕES. A PRIMEIRA TAREFA É SALVAR OS
; VALORES DE "W" E "STATUS" PARA RECUPERAÇÃO FUTURA

	ORG	0x04			;ENDEREÇO INICIAL DA INTERRUPÇÃO
	MOVWF	W_TEMP		;COPIA W PARA W_TEMP
	SWAPF	STATUS,W
	MOVWF	STATUS_TEMP	;COPIA STATUS PARA STATUS_TEMP

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                    ROTINA DE INTERRUPÇÃO                        *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
; AQUI SERÃO ESCRITAS AS ROTINAS DE RECONHECIMENTO E TRATAMENTO DAS
; INTERRUPÇÕES
	MOVLW .212  ;TMR0 <- 212
	MOVWF TMR0  ;SETA TMR0 PARA CONTAR APROXIMADAMENTE 100U
	
	
	BTFSS FLAG_VERIFICADOR_CICLO, 2  ;CHECA SE ESTÁ NO MEIO DE UM PERÍODO OU NÃO
	CALL CONFIGURA_PERIODO           ;CASO NÃO ESTIVER, CONFIGURA O PERIODO
	
	;CHECA SE ESTAMOS NA PARTE APAGADA OU ACESA DO PERIODO
	BTFSS GPIO, GP5
	GOTO LED_APAGADO
	GOTO LED_ACESO
	
	;DECREMENTA A VERIAVEL DE TEMPOS DO LED ATÉ QUE ELE POSSA SER APAGADO
	LED_ACESO	
	    DECFSZ TEMPO_LIGADO
	    GOTO TRATAINT
	    BCF GPIO, GP5
	    GOTO TRATAINT
	    
	;DECREMENTA A VARIAVEL DE TEMPOS DO LED ATÉ QUE ELE POSSA SER ACESO (E RECONIFURADO) NOVAMENTE
	LED_APAGADO
	    DECFSZ TEMPO_DESLIGADO
	    GOTO TRATAINT
	    CALL CONFIGURA_PERIODO
	    GOTO LED_ACESO
	    
	TRATAINT
	    BCF INTCON, T0IF ;Zerando a flag de overflow

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                 ROTINA DE SAÍDA DA INTERRUPÇÃO                  *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
; OS VALORES DE "W" E "STATUS" DEVEM SER RECUPERADOS ANTES DE 
; RETORNAR DA INTERRUPÇÃO

SAI_INT
	SWAPF	STATUS_TEMP,W
	MOVWF	STATUS		;MOVE STATUS_TEMP PARA STATUS
	SWAPF	W_TEMP,F
	SWAPF	W_TEMP,W	;MOVE W_TEMP PARA W
	RETFIE

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*	            	 ROTINAS E SUBROTINAS                      *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
; CADA ROTINA OU SUBROTINA DEVE POSSUIR A DESCRIÇÃO DE FUNCIONAMENTO
; E UM NOME COERENTE ÀS SUAS FUNÇÕES.

	
	
;FAZ A CHECAGEM DO NÍVEL DE TENSÃO NECESSÁRIO PARA SETAR O COMPARADOR
RECONFIGURAR_COMPARADOR
    
    TESTE_CMP_0
	MOVFW CONFIG_COMPARADOR
	SUBLW .0
	BTFSS STATUS, Z
	GOTO TESTE_CMP_1
	
	BCF INTCON, GIE
	BANK1
	MOVLW   B'10100010' 
	MOVWF   VRCON		;Low range - N=2 0.5V (0.416667V)
	BANK0				;RETORNA PARA O BANCO 0
	BSF INTCON, GIE
	
	RETURN
	
    TESTE_CMP_1
	MOVFW CONFIG_COMPARADOR
	SUBLW .1
	BTFSS STATUS, Z
	GOTO TESTE_CMP_2
	
	BCF INTCON, GIE
	BANK1
	MOVLW   B'10100101' 
	MOVWF   VRCON		;Low range - N=5 1V (1.041666667V)
	BANK0				;RETORNA PARA O BANCO 0
	BSF INTCON, GIE
	
	RETURN
	
    TESTE_CMP_2
	MOVFW CONFIG_COMPARADOR
	SUBLW .2
	BTFSS STATUS, Z
	GOTO TESTE_CMP_3
	
	BCF INTCON, GIE
	BANK1
	MOVLW   B'10100111' 
	MOVWF   VRCON		;Low range - N=7 1.5V (1.45833333V)
	BANK0				;RETORNA PARA O BANCO 0
	BSF INTCON, GIE
	
	RETURN
	
    TESTE_CMP_3
	MOVFW CONFIG_COMPARADOR
	SUBLW .3
	BTFSS STATUS, Z
	GOTO TESTE_CMP_4
	
	BCF INTCON, GIE
	BANK1
	MOVLW   B'10000101' 
	MOVWF   VRCON		;HIGH range - N=5 2V (2,03125V)
	BANK0				;RETORNA PARA O BANCO 0
	BSF INTCON, GIE
	
	RETURN
	
    TESTE_CMP_4
	MOVFW CONFIG_COMPARADOR
	SUBLW .4
	BTFSS STATUS, Z
	GOTO TESTE_CMP_5
	
	BCF INTCON, GIE
	BANK1
	MOVLW   B'10101100'  
	MOVWF   VRCON		;low range - N=12 2.5V (2,5V)
	BANK0				;RETORNA PARA O BANCO 0
	BSF INTCON, GIE
	
	RETURN
	
    TESTE_CMP_5
	MOVFW CONFIG_COMPARADOR
	SUBLW .5
	BTFSS STATUS, Z
	GOTO TESTE_CMP_6
	
	BCF INTCON, GIE
	BANK1
	MOVLW   B'10001011' 
	MOVWF   VRCON		;HIGH range - N=11 3V (2,96875V)
	BANK0				;RETORNA PARA O BANCO 0
	BSF INTCON, GIE
	
	RETURN
	
    TESTE_CMP_6
	MOVFW CONFIG_COMPARADOR
	SUBLW .6
	BTFSS STATUS, Z
	GOTO ERROR_CMP
	
	BCF INTCON, GIE
	BANK1
	MOVLW   B'10001110' 
	MOVWF   VRCON		;HIGH range - N=14 3.5V (3,4375V)
	BANK0
	BSF INTCON, GIE
	
	RETURN
    
    ERROR_CMP
	CLRF GPIO      ;DEIXA GPIO ZERADO
	CLRF FLAG_VERIFICADOR_CICLO   ;SEM TER TESTADO NADA
	CLRF CONFIG_COMPARADOR    ;COMEÇA COM O COMPARADOR PARA 0,5V
	
	RETURN
		
ATUALIZAR_CICLO
    
	BCF INTCON, GIE  ;DESATIVA INTERRUPÇÃO PARA ACESSAR REGIÃO CRÍTICA
    
	MOVFW CONFIG_COMPARADOR
	MOVWF SELECIONA_DUTY
	
	BTFSS FLAG_VERIFICADOR_CICLO, 0  ;VERIFICA SE ESATAVA SUBINDO 
	INCF SELECIONA_DUTY  ;CASO ESTIVESSE DESCENDO, O CICLO SELECIONADO É O SUPERIOR
	
	BCF FLAG_VERIFICADOR_CICLO, 0 ;LIMPA A FLAG DE TESTE
	BCF FLAG_VERIFICADOR_CICLO, 1 ;LIMPA A FLAG DE SUBIDA
	
	BSF INTCON, GIE ;REATIVA INTERRUPÇÃO
	
	RETURN

LED_DESLIGADO
	
	BCF FLAG_VERIFICADOR_CICLO, 2  ;DESATIVA A FLAG DE CICLOS DE PERÍDOS
	
	;DESLIGA INTERRUPÇÕES
	MOVLW	B'00000000';
	MOVWF	INTCON		;DEFINE OPÇÕES DE INTERRUPÇÕES
	
	BCF GPIO, GP5  ;DESLIGA LED
	CHECAGEM_0
	    BTFSS CMCON, COUT  ;TESTA SE A TENSÃO PASSOU DE 0,5V
	    GOTO CHECAGEM_0   ;SE NÃO, VOLTA PARA A CHEGAEM
	    
	BSF FLAG_VERIFICADOR_CICLO, 1  ;FOI REALIZADO UM TESTE
	BSF FLAG_VERIFICADOR_CICLO, 0  ;A TENSÃO ESTÁ SUBINDO
	
	;RELIGA AS INTERRUPÇÕES
	MOVLW	B'10100000';
	MOVWF	INTCON		;DEFINE OPÇÕES DE INTERRUPÇÕES
	
	;SETA UMA MARGEM DE 260 MICRO PARA ACHAR A NOVA TENSÃO ATÉ QUE A INTERRUPÇÃO SEJA CHAMADA
	MOVLW .126 
	MOVWF TMR0
	
	RETURN
	
LED_LIGADO
	
	BCF FLAG_VERIFICADOR_CICLO, 2  ;DESATIVA A FLAG DE CICLOS DE PERÍDOS
	
	;DESLIGA INTERRUPÇÕES
	MOVLW	B'00000000';
	MOVWF	INTCON		;DEFINE OPÇÕES DE INTERRUPÇÕES
	
	BSF GPIO, GP5  ;LIGA LED
	CHECAGEM_7
	    BTFSC CMCON, COUT  ;TESTA SE A TENSÃO BAIXOU PARA MENOS DE 3,5V
	    GOTO CHECAGEM_7   ;SE NÃO, VOLTA PARA A CHEGAEM
	    
	BSF FLAG_VERIFICADOR_CICLO, 1  ;FOI REALIZADO UM TESTE
	BCF FLAG_VERIFICADOR_CICLO, 0  ;A TENSÃO ESTÁ DESCENDO
	
	;RELIGA AS INTERRUPÇÕES
	MOVLW	B'10100000';
	MOVWF	INTCON		;DEFINE OPÇÕES DE INTERRUPÇÕES
	
	;SETA UMA MARGEM DE 260 MICRO PARA ACHAR A NOVA TENSÃO ATÉ QUE A INTERRUPÇÃO SEJA CHAMADA
	MOVLW .126 
	MOVWF TMR0
	
	RETURN
	
;CONFIGURA A QUANTIDADE DE TEMPOS NECESSÁRIA PARA O LED LIDGADO E DESLIGADO DEPENDENDO DO DUTY REQUERIDO
CONFIGURA_PERIODO
	
	;TESTA SE O DUTY SELECIONADO É DE 5%
	TESTE_CL_1
	    MOVFW SELECIONA_DUTY
	    SUBLW .1
	    BTFSS STATUS, Z
	    GOTO TESTE_CL_2
	    
	    MOVLW .2       ;1+1
	    MOVWF TEMPO_LIGADO
	    MOVLW .19       ;19
	    MOVWF TEMPO_DESLIGADO
	    
	    BSF FLAG_VERIFICADOR_CICLO, 2
	    
	    BSF GPIO, GP5
	    RETURN
	;TESTA SE O DUTY SELECIONADO É DE 10%  
	TESTE_CL_2
	    MOVFW SELECIONA_DUTY
	    SUBLW .2
	    BTFSS STATUS, Z
	    GOTO TESTE_CL_3
	    
	    MOVLW .3	    ;2+1
	    MOVWF TEMPO_LIGADO
	    MOVLW .18     ;18
	    MOVWF TEMPO_DESLIGADO
	    
	    BSF FLAG_VERIFICADOR_CICLO, 2
	    
	    BSF GPIO, GP5
	    RETURN
	 
	;TESTA SE O DUTY SELECIONADO É DE 20%
	TESTE_CL_3
	    MOVFW SELECIONA_DUTY
	    SUBLW .3
	    BTFSS STATUS, Z
	    GOTO TESTE_CL_4
	    
	    MOVLW .5    ;4+1
	    MOVWF TEMPO_LIGADO
	    MOVLW .16  ;16
	    MOVWF TEMPO_DESLIGADO
	    
	    BSF FLAG_VERIFICADOR_CICLO, 2
	    
	    BSF GPIO, GP5
	    RETURN
	 
	;TESTA SE O DUTY SELECIONADO É DE 30%
	TESTE_CL_4
	    MOVFW SELECIONA_DUTY
	    SUBLW .4
	    BTFSS STATUS, Z
	    GOTO TESTE_CL_5
	    
	    MOVLW .7	   ;6+1
	    MOVWF TEMPO_LIGADO
	    MOVLW .14	    ;14
	    MOVWF TEMPO_DESLIGADO
	    
	    BSF FLAG_VERIFICADOR_CICLO, 2
	    
	    BSF GPIO, GP5
	    RETURN
	    
	;TESTA SE O DUTY SELECIONADO É DE 40%    
	TESTE_CL_5
	    MOVFW SELECIONA_DUTY
	    SUBLW .5
	    BTFSS STATUS, Z
	    GOTO TESTE_CL_6
	    
	    MOVLW .9	    ;8+1
	    MOVWF TEMPO_LIGADO
	    MOVLW .12	    ;12
	    MOVWF TEMPO_DESLIGADO
	    
	    BSF FLAG_VERIFICADOR_CICLO, 2
	    
	    BSF GPIO, GP5
	    RETURN
	    
	;TESTA SE O DUTY SELECIONADO É DE 80%
	TESTE_CL_6
	    MOVFW SELECIONA_DUTY
	    SUBLW .6
	    BTFSS STATUS, Z
	    GOTO ERROR_CL
	    
	    MOVLW .17	    ;16+1
	    MOVWF TEMPO_LIGADO
	    MOVLW .4	    ;4
	    MOVWF TEMPO_DESLIGADO
	    
	    BSF FLAG_VERIFICADOR_CICLO, 2
	    
	    BSF GPIO, GP5
	    RETURN
	   
	ERROR_CL
	    RETURN
	
	
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                     INICIO DO PROGRAMA                          *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
	
INICIO
	BANK1				;ALTERA PARA O BANCO 1
	MOVLW	B'00000010' ;CONFIGURA TODAS AS PORTAS DO GPIO (PINOS),
	MOVWF	TRISIO		;COMO SAÍDAS, E GP1 COMO ENTRADA
	MOVLW	B'00000010' ;CONFIGURA TODAS AS PORTAS DO GPIO (PINOS)
	MOVLW	ANSEL 		;DEFINE PORTAS COMO Digital I/O, MENOS GP1, QUE ESTÁ COMO ANALOG
	MOVLW	B'00000000'
	MOVWF	OPTION_REG	;DEFINE OPÇÕES DE OPERAÇÃO
	MOVLW	B'10100000'     ;
	MOVWF	INTCON		;DEFINE OPÇÕES DE INTERRUPÇÕES
	MOVLW   B'10100010' 
	MOVWF   VRCON		;Low range - N=2
	BANK0				;RETORNA PARA O BANCO 0
	MOVLW	B'00010011'
	MOVWF	CMCON		;DEFINE O MODO DE OPERAÇÃO DO COMPARADOR ANALÓGICO

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                     INICIALIZAÇÃO DAS VARIÁVEIS                 *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
	CLRF GPIO      ;DEIXA GPIO ZERADO
	CLRF FLAG_VERIFICADOR_CICLO   ;SEM TER TESTADO NADA
	CLRF CONFIG_COMPARADOR    ;COMEÇA COM O COMPARADOR PARA 0,5V
	

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                     ROTINA PRINCIPAL                            *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
MAIN
	;CORPO DA ROTINA PRINCIPAL
	
	CALL LED_DESLIGADO
	
	
	TESTA_TENSAO
		BTFSC CMCON, COUT  ;TESTA SE A TENSÃO É MENOR QUE O LIMIAR
		GOTO MAIOR
		
		MENOR
		
		    ;TESTE PARA VER SE É MENOR QUE O MENOR LIMIAR
		    MOVFW CONFIG_COMPARADOR
		    SUBLW .0
		    BTFSS STATUS, Z
		    GOTO MAIOR_QUE_0.5
		    
		    CALL LED_DESLIGADO
		    GOTO TESTA_TENSAO
		    
		    MAIOR_QUE_0.5
		
			BTFSS FLAG_VERIFICADOR_CICLO, 1 ;VERIFICA SE JÁ FORAM FEITOS TESTES
			GOTO DESCENDO_TENSAO   ;CASO NÃO, SETAR FLAGS E FAZER TESTE DE TENSÃO MENOR
			BTFSS FLAG_VERIFICADOR_CICLO, 0; CASO SIM, CHECA SE A TENSÃO ESTÁ SUBINDO OU DESCENDO
			GOTO DESCENDO_TENSAO   ;SE ESTIVER DESCENDO, VAI PARA TESTAR A PROXIMA

			;SE ESTIVER SUBINDO, CHEGAMOS NO PONTO
			CALL ATUALIZAR_CICLO
			GOTO TESTA_TENSAO

			DESCENDO_TENSAO
			    BSF FLAG_VERIFICADOR_CICLO, 1  ;FOI REALIZADO UM TESTE
			    BCF FLAG_VERIFICADOR_CICLO, 0  ;A TENSÃO ESTÁ DESCENDO
			    DECF CONFIG_COMPARADOR
			    CALL RECONFIGURAR_COMPARADOR
			    GOTO TESTA_TENSAO
		    
		MAIOR
		
		    ;TESTE PARA VER SE É MAIOR QUE O MAIOR LIMIAR
		    MOVFW CONFIG_COMPARADOR
		    SUBLW .6
		    BTFSS STATUS, Z
		    GOTO MENOR_QUE_3.5
		    
		    CALL LED_LIGADO
		    GOTO TESTA_TENSAO
		
		    MENOR_QUE_3.5
		
			BTFSS FLAG_VERIFICADOR_CICLO, 1 ;VERIFICA SE JÁ FORAM FEITOS TESTES
			GOTO SUBINDO_TENSAO    ;CASO NÃO, SETAR FLAGS E FAZER TESTE DE TENSÃO MAIOR
			BTFSC FLAG_VERIFICADOR_CICLO, 0; CASO SIM, CHECA SE A TENSÃO ESTÁ DESCENDO
			GOTO SUBINDO_TENSAO  ;SE ESTIVER SUBINDO, VAI PARA TESTAR A PROXIMA

			;SE ESTIVER DESCENDO, CHEGAMOS NO PONTO
			CALL ATUALIZAR_CICLO
			GOTO TESTA_TENSAO

			SUBINDO_TENSAO
			    BSF FLAG_VERIFICADOR_CICLO, 1  ;FOI REALIZADO UM TESTE
			    BSF FLAG_VERIFICADOR_CICLO, 0  ;A TENSÃO ESTÁ SUBINDO
			    INCF CONFIG_COMPARADOR
			    CALL RECONFIGURAR_COMPARADOR
			    GOTO TESTA_TENSAO
				    
		    
	    
	GOTO	MAIN

;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
;*                       FIM DO PROGRAMA                           *
;* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *

	END
